"""Trusted domain guidance for evidence-backed novel analysis."""

from __future__ import annotations


def build_novel_analysis_method_guidance() -> str:
    """Return the shared analysis method without prescribing a fixed plan."""

    return (
        "【小说来源分析方法】\n"
        "- 根据用户问题和已读取证据选择必要的分析视角，不为显得完整而凑齐所有视角。\n"
        "- 区分四个层次：原文实际出现的表达、故事世界中可确认的事实、角色当时掌握或"
        "相信的信息、分析者基于证据作出的解释。不得把角色说法或分析解释写成确定事实；"
        "冲突、缺口和歧义应明确保留。\n"
        "- 故事动力可从人物目标、阻力、选择、代价、因果链、关键转折和未解决问题分析；"
        "人物可从欲望、认知边界、关系变化、行动一致性和变化轨迹分析。\n"
        "- 叙事组织可从叙述视角与聚焦、可靠性、时间顺序、信息释放、结构层次、场景功能、"
        "节奏和转场分析。\n"
        "- 表达技法可从冲突与悬念、对白与潜台词、描写与措辞、意象与反复、伏笔与回收分析；"
        "主题或阅读效果必须由反复出现且相互支持的文本证据推出，不臆测作者意图。\n"
        "- 提炼可复用写作技法时，按叙事结构、人物塑造、视角与信息控制、节奏与张力、"
        "语言与文风、对话设计、意象与氛围、主题与象征分类；合并同类观察，不为凑数拆成"
        "零散技法。每项只写通用的写作逻辑和风格特征。\n"
        "- 技法描述不得带入作品名、人物、地点、专有设定、具体情节或引文。原文证据只放在"
        "独立证据字段中，用于审核，不进入可复用写作 Skill 的正文。\n"
        "- 尚未读取正文时不得预设作品结论；读取后让证据决定结论，"
        "并优先回答用户明确提出的重点。"
    )


__all__ = ["build_novel_analysis_method_guidance"]
